    /**
     * Runs the real-ping batch test for every server in [groupId], independent
     * of the currently selected group. Used by the Chain free-servers refresh.
     */
    fun testGroupRealPing(groupId: String, onlyTcp: Boolean = false) {
        dataSource.cancelAllPing()
        val servers = mutableServerGroupState(groupId).value.servers
        if (servers.isEmpty()) {
            _uiState.update { it.copy(isTesting = false) }
            return
        }
        val serverGuids = servers.map { it.guid }
        mutableServerGroupState(groupId).update { current ->
            current.copy(
                servers = current.servers.map { server ->
                    if (server.testDelayMillis == 0L) server
                    else server.copy(testDelayMillis = 0L)
                },
                rows = current.rows.map { row ->
                    if (row.testDelayMillis == 0L) row
                    else row.copy(testDelayMillis = 0L)
                }
            )
        }
        testingGroupId = groupId
        _uiState.update {
            it.copy(
                isTesting = true,
                status = MainStatus.Testing
            )
        }
        viewModelScope.launch(ioDispatcher) {
            dataSource.clearAllTestDelayResults(serverGuids)
            cacheMutex.withLock { groupDataCache.remove(groupId) }
            dataSource.sendMsg2TestService(
                TestServiceMessage(
                    key = AppConfig.MSG_MEASURE_CONFIG_START,
                    subscriptionId = groupId,
                    serverGuids = if (keywordFilter.isNotEmpty()) serverGuids else emptyList(),
                    onlyTcp = onlyTcp
                )
            )
        }
    }

