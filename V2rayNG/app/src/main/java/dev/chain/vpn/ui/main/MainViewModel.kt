    // ---------- Chain free servers ----------
    private var freeServersJob: Job? = null

    /**
     * One-tap refresh of the "chain-free" subscription: downloads the free
     * server list with caching disabled, replaces the previously imported
     * servers, switches the UI to the free group, and auto-selects the first
     * server so connect works immediately. Ping tests are manual-only.
     */
    private fun refreshFreeServers() {
        if (freeServersJob?.isActive == true) return
        freeServersJob = viewModelScope.launch(ioDispatcher) {
            try {
                _uiState.update {
                    it.copy(
                        freeServersState = FreeServersState.Working(
                            dataSource.getString(R.string.chain_free_phase_download)
                        ),
                        freeServersLastUpdated = ChainFreeServers.lastUpdatedMillis()
                    )
                }
                when (val result = ChainFreeServers.refresh()) {
                    is ChainFreeServers.RefreshResult.Success -> {
                        _uiState.update {
                            it.copy(freeServersLastUpdated = ChainFreeServers.lastUpdatedMillis())
                        }
                        setupGroupTab(forceRefresh = true).join()
                        refreshSelectedGuid()
                        val subId = ChainFreeServers.SUB_ID
                        if (_uiState.value.groups.any { it.id == subId }) {
                            dataSource.setSelectedSubscriptionId(subId)
                            _uiState.update { it.copy(selectedGroupId = subId) }
                            updateGroupUi(subId, loadGroup(subId, forceRefresh = true))
                            // Auto-select the first server so the connect button works
                            // right away. Ping tests are manual-only (no auto test).
                            mutableServerGroupState(subId).value.servers
                                .firstOrNull()?.guid?.let { updateSelectedGuid(it) }
                        }
                        _uiState.update {
                            it.copy(freeServersState = FreeServersState.Success(result.count))
                        }
                        toast(dataSource.getString(R.string.chain_free_success, result.count))
                    }

                    is ChainFreeServers.RefreshResult.Failure -> {
                        val resId = when (result.kind) {
                            ChainFreeServers.FailureKind.NETWORK -> R.string.chain_free_error_network
                            ChainFreeServers.FailureKind.EMPTY -> R.string.chain_free_error_empty
                            ChainFreeServers.FailureKind.PARSE -> R.string.chain_free_error_parse
                        }
                        val message = dataSource.getString(resId)
                        _uiState.update { it.copy(freeServersState = FreeServersState.Error(message)) }
                        toastError(message)
                    }
                }
            } catch (cancelled: CancellationException) {
                throw cancelled
            } catch (e: Exception) {
                LogUtil.e(AppConfig.TAG, "Free servers refresh failed", e)
                _uiState.update {
                    it.copy(
                        freeServersState = FreeServersState.Error(
                            dataSource.getString(R.string.chain_free_error_network)
                        )
                    )
                }
            }
        }
    }

    // ---------- Live connection statistics ----------
    private val _connectionStats = MutableStateFlow<ConnectionStats?>(null)
    val connectionStats: StateFlow<ConnectionStats?> = _connectionStats.asStateFlow()

    private var statsJob: Job? = null
    private var statsConnectEpochSec = 0L
    private var statsLastUp = 0L
    private var statsLastDown = 0L
    private var statsSessionUp = 0L
    private var statsSessionDown = 0L

    private fun startStatsPolling() {
        stopStatsPolling()
        statsConnectEpochSec = System.currentTimeMillis() / 1000L
        statsLastUp = 0L
        statsLastDown = 0L
        statsSessionUp = 0L
        statsSessionDown = 0L
        statsJob = viewModelScope.launch(ioDispatcher) {
            while (isActive) {
                try {
                    var up = 0L
                    var down = 0L
                    dataSource.queryTrafficStats().forEach { stat ->
                        if (stat.tag == AppConfig.TAG_BLOCKED || stat.tag == AppConfig.TAG_DIRECT) {
                            return@forEach
                        }
                        when (stat.direction) {
                            AppConfig.UPLINK -> up += stat.value
                            AppConfig.DOWNLINK -> down += stat.value
                        }
                    }
                    val (upSpeed, downSpeed) = when {
                        up < statsLastUp || down < statsLastDown -> 0L to 0L // counters reset
                        statsLastUp == 0L && statsLastDown == 0L -> 0L to 0L // first sample
                        else -> (up - statsLastUp).coerceAtLeast(0L) to
                                (down - statsLastDown).coerceAtLeast(0L)
                    }
                    statsLastUp = up
                    statsLastDown = down
                    statsSessionUp += upSpeed
                    statsSessionDown += downSpeed
                    _connectionStats.value = ConnectionStats(
                        upBps = upSpeed,
                        downBps = downSpeed,
                        connectedSeconds = (System.currentTimeMillis() / 1000L - statsConnectEpochSec)
                            .coerceAtLeast(0L),
                        sessionUpBytes = statsSessionUp,
                        sessionDownBytes = statsSessionDown
                    )
                } catch (cancelled: CancellationException) {
                    throw cancelled
                } catch (e: Exception) {
                    LogUtil.e(AppConfig.TAG, "Connection stats polling failed", e)
                }
                delay(1000)
            }
        }
    }

    private fun stopStatsPolling() {
        statsJob?.cancel()
        statsJob = null
        _connectionStats.value = null
    }

    private fun onTestsFinished() {
        viewModelScope.launch(ioDispatcher) {
            cacheMutex.withLock { groupDataCache.clear() }
            testingGroupId = null
            _uiState.update {
                it.copy(
                    isTesting = false,
                    status = if (it.isRunning) MainStatus.Connected else MainStatus.Disconnected
                )
            }
            reloadAllGroups(_uiState.value.groups.map { it.id })
        }
    }

    fun triggerLocateSelectedServer() {
        val selected = dataSource.getSelectServer() ?: return
        val profile = dataSource.decodeServerConfig(selected) ?: return
        val groupId = profile.subscriptionId
        if (_uiState.value.groups.none { it.id == groupId }) return
        viewModelScope.launch(ioDispatcher) {
            updateGroupUi(groupId, loadGroup(groupId))
            if (_uiState.value.selectedGroupId != groupId) {
                dataSource.setSelectedSubscriptionId(groupId)
            }
            val target = LocateTarget(groupId, selected)
            _uiState.update {
                it.copy(selectedGroupId = groupId, locateTarget = target)
            }
        }
    }

    private fun consumeLocateTarget() {
        _uiState.update { it.copy(locateTarget = null) }
    }

    // ---------- Running state ----------
    private fun updateRunningState(running: Boolean, clearTestingText: Boolean = true) {
        _uiState.update { state ->
            state.copy(
                isRunning = running,
                status = if (!clearTestingText && state.isTesting) state.status
                else if (running) MainStatus.Connected else MainStatus.Disconnected
            )
        }
        if (running) startStatsPolling() else stopStatsPolling()
    }

    override fun onCleared() {
        setupGroupJob?.cancel()
        preloadJob?.cancel()
        selectedGroupLoadJob?.cancel()
        reloadJob?.cancel()
        filterJob?.cancel()
        freeServersJob?.cancel()
        stopStatsPolling()
        cancelAllPing()
        dataSource.close()
        super.onCleared()
    }

